//! Snapshot and behaviour tests for `engine: mysql`.
//!
//! The PostgreSQL equivalents live in `tests/codegen.rs`; this file covers the
//! places where the two backends genuinely diverge — driver types, `?`
//! placeholders, `:execlastid`, and the MySQL type table.

use buffa::Message as _;
use sqlc_gen_sqlx::plugin::{
    Catalog, Column, Enum, GenerateRequest, GenerateResponse, Identifier, Parameter, Query, Schema,
    Settings, Table,
};
use sqlc_gen_sqlx::run_with_bytes;

fn column(name: &str, db_type: &str, not_null: bool) -> Column {
    Column {
        name: name.to_string(),
        r#type: Some(Identifier {
            name: db_type.to_string(),
            ..Default::default()
        })
        .into(),
        not_null,
        ..Default::default()
    }
}

/// A `sqlc.slice()` parameter. `name` is the slice's own name (and the one in
/// the `/*SLICE:name*/` marker); `original_name` is the column it is compared
/// against.
fn slice_column(name: &str, original_name: &str, db_type: &str) -> Column {
    Column {
        is_sqlc_slice: true,
        is_named_param: true,
        original_name: original_name.to_string(),
        ..column(name, db_type, true)
    }
}

fn param(number: i32, col: Column) -> Parameter {
    Parameter {
        number,
        column: Some(col).into(),
        ..Default::default()
    }
}

fn authors_table() -> Table {
    Table {
        rel: Some(Identifier {
            name: "authors".to_string(),
            ..Default::default()
        })
        .into(),
        columns: vec![
            column("id", "bigint", true),
            column("name", "varchar(255)", true),
            column("bio", "text", false),
        ],
        ..Default::default()
    }
}

fn generate(engine: &str, queries: Vec<Query>) -> Result<String, String> {
    generate_with(engine, queries, vec![])
}

fn generate_with(engine: &str, queries: Vec<Query>, enums: Vec<Enum>) -> Result<String, String> {
    let request = GenerateRequest {
        settings: Some(Settings {
            engine: engine.to_string(),
            ..Default::default()
        })
        .into(),
        catalog: Some(Catalog {
            default_schema: "sqlc_test".to_string(),
            schemas: vec![Schema {
                name: "sqlc_test".to_string(),
                tables: vec![authors_table()],
                enums,
                ..Default::default()
            }],
            ..Default::default()
        })
        .into(),
        queries,
        plugin_options: b"{}".to_vec(),
        sqlc_version: "1.0.0-test".to_string(),
        ..Default::default()
    };

    let out = run_with_bytes(&request.encode_to_vec()).map_err(|e| e.to_string())?;
    let resp = GenerateResponse::decode_from_slice(&out).expect("decode response");
    Ok(String::from_utf8(resp.files[0].contents.clone()).expect("utf-8 output"))
}

fn assert_snapshot(name: &str, code: &str) {
    let mut settings = insta::Settings::clone_current();
    settings.add_filter(
        r"// Code generated by sqlc-gen-sqlx v[0-9A-Za-z][0-9A-Za-z.+-]*\. DO NOT EDIT\.",
        "// Code generated by sqlc-gen-sqlx v[VERSION]. DO NOT EDIT.",
    );
    settings.add_filter(
        r"// sqlc version: [0-9A-Za-z][0-9A-Za-z.+-]*",
        "// sqlc version: [VERSION]",
    );
    settings.bind(|| insta::assert_snapshot!(name, code));
}

#[test]
fn as_executor_targets_the_mysql_driver() {
    let code = generate("mysql", vec![]).expect("generate");
    assert_snapshot("mysql_as_executor", &code);
    for expected in [
        "Database = sqlx::MySql",
        "impl AsExecutor for sqlx::MySqlPool",
        "impl AsExecutor for sqlx::MySqlConnection",
        "sqlx::Transaction<'_, sqlx::MySql>",
        "sqlx::pool::PoolConnection<sqlx::MySql>",
    ] {
        assert!(code.contains(expected), "missing {expected} in:\n{code}");
    }
    assert!(!code.contains("Pg"), "leaked a PostgreSQL type in:\n{code}");
}

#[test]
fn one_maps_mysql_column_types() {
    let query = Query {
        name: "GetAuthor".to_string(),
        cmd: ":one".to_string(),
        text: "SELECT id, name, bio FROM authors WHERE id = ?".to_string(),
        columns: vec![
            column("id", "bigint", true),
            column("name", "varchar(255)", true),
            column("bio", "text", false),
        ],
        params: vec![param(1, column("id", "bigint", true))],
        ..Default::default()
    };
    let code = generate("mysql", vec![query]).expect("generate");
    assert_snapshot("mysql_one", &code);
    assert!(
        code.contains("pub id: i64"),
        "expected i64 id field in:\n{code}"
    );
    assert!(
        code.contains("pub name: String"),
        "expected varchar(255) to map to String in:\n{code}"
    );
    assert!(
        code.contains("pub bio: Option<String>"),
        "expected nullable text to map to Option<String> in:\n{code}"
    );
}


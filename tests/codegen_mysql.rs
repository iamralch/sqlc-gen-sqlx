#[test]
fn execlastid_needs_no_returning_columns() {
    // The PostgreSQL generator requires a RETURNING column here; MySQL reads
    // the key off the query result, so a column-less query must still work.
    let query = Query {
        name: "CreateAuthor".to_string(),
        cmd: ":execlastid".to_string(),
        text: "INSERT INTO authors (name) VALUES (?)".to_string(),
        params: vec![param(1, column("name", "text", true))],
        columns: vec![],
        ..Default::default()
    };
    generate("mysql", vec![query.clone()]).expect("mysql :execlastid without columns");

    let err = generate("postgresql", vec![query]).expect_err("postgres needs RETURNING");
    assert!(
        err.contains("RETURNING"),
        "expected a RETURNING hint in: {err}"
    );
}

#[test]
fn slice_param_expands_into_ordinal_placeholders() {
    // Mirrors what sqlc reports: it lifts `sqlc.slice()` out of the ordinal
    // numbering, so the slice carries the *higher* number despite coming first
    // in the text, and its column name is the slice's own (`ids`) while
    // `original_name` is the compared column (`id`).
    let query = Query {
        name: "ListAuthorsByIds".to_string(),
        cmd: ":many".to_string(),
        text: "SELECT id, name FROM authors WHERE id IN (/*SLICE:ids*/?) AND name = ?".to_string(),
        columns: vec![
            column("id", "bigint", true),
            column("name", "varchar", true),
        ],
        params: vec![
            param(2, slice_column("ids", "id", "bigint")),
            param(1, column("name", "varchar", true)),
        ],
        ..Default::default()
    };
    let code = generate("mysql", vec![query]).expect("generate");
    assert_snapshot("mysql_slice_param", &code);
    assert!(
        code.contains(r#"sql.replace("/*SLICE:ids*/?", &replacement)"#),
        "expected the slice marker to be rewritten in:\n{code}"
    );
    assert!(
        code.contains(r#"repeat_n("?", slice_len)"#),
        "expected ordinal placeholder expansion in:\n{code}"
    );
    // Ordinal placeholders are bound in text order, so the slice binds before
    // the scalar even though sqlc numbered it second.
    let slice_bind = code.find("for value in arg.id").expect("slice bind");
    let scalar_bind = code.find("query.bind(arg.name)").expect("scalar bind");
    assert!(
        slice_bind < scalar_bind,
        "slice must bind before the trailing scalar in:\n{code}"
    );
    // Ordinal placeholders keep their positions, so nothing gets renumbered.
    assert!(
        !code.contains("__SQLC_PARAM_"),
        "MySQL must not renumber placeholders in:\n{code}"
    );
}

#[test]
fn enums_omit_the_postgres_type_name_attribute() {
    let status = Enum {
        name: "authors_status".to_string(),
        vals: vec!["active".to_string(), "banned".to_string()],
        ..Default::default()
    };
    let query = Query {
        name: "GetStatus".to_string(),
        cmd: ":one".to_string(),
        text: "SELECT status FROM authors WHERE id = ?".to_string(),
        columns: vec![column("status", "authors_status", true)],
        params: vec![param(1, column("id", "bigint", true))],
        ..Default::default()
    };
    let code = generate_with("mysql", vec![query], vec![status]).expect("generate");
    assert_snapshot("mysql_enum", &code);
    assert!(
        code.contains("pub enum AuthorsStatus"),
        "expected the enum type in:\n{code}"
    );
    assert!(
        code.contains(r#"#[sqlx(rename = "active")]"#),
        "expected variant renames in:\n{code}"
    );
    assert!(
        !code.contains("type_name"),
        "MySQL enums must not carry #[sqlx(type_name)] in:\n{code}"
    );
}

#[test]
fn copyfrom_builds_a_mysql_query_builder() {
    let query = Query {
        name: "BulkCreateAuthors".to_string(),
        cmd: ":copyfrom".to_string(),
        text: "INSERT INTO authors (name, bio) VALUES (?, ?)".to_string(),
        params: vec![
            param(1, column("name", "varchar(255)", true)),
            param(2, column("bio", "text", false)),
        ],
        ..Default::default()
    };
    let code = generate("mysql", vec![query]).expect("generate");
    assert_snapshot("mysql_copyfrom", &code);
    let builder = code.split_whitespace().collect::<Vec<_>>().join(" ");
    assert!(
        builder.contains("sqlx::QueryBuilder::< sqlx::MySql, >::new"),
        "expected a MySQL query builder in:\n{code}"
    );
}

#[test]
fn covers_the_mysql_scalar_type_table() {
    let cases: &[(&str, &str)] = &[
        ("tinyint", "i8"),
        ("tinyint unsigned", "u8"),
        ("smallint", "i16"),
        ("mediumint", "i32"),
        ("int(11)", "i32"),
        ("int unsigned", "u32"),
        ("bigint", "i64"),
        ("bigint unsigned", "u64"),
        ("boolean", "bool"),
        ("float", "f32"),
        ("double", "f64"),
        ("decimal(10,2)", "bigdecimal::BigDecimal"),
        ("char(3)", "String"),
        ("varchar(255)", "String"),
        ("longtext", "String"),
        ("varbinary(16)", "Vec<u8>"),
        ("longblob", "Vec<u8>"),
        ("json", "serde_json::Value"),
        ("timestamp", "chrono::DateTime<chrono::Utc>"),
        ("datetime", "chrono::NaiveDateTime"),
        ("date", "chrono::NaiveDate"),
        ("time", "chrono::NaiveTime"),
    ];

    let columns = cases
        .iter()
        .enumerate()
        .map(|(i, (db_type, _))| column(&format!("c{i}"), db_type, true))
        .collect::<Vec<_>>();
    let query = Query {
        name: "AllTypes".to_string(),
        cmd: ":one".to_string(),
        text: "SELECT * FROM all_types".to_string(),
        columns,
        ..Default::default()
    };
    let code = generate("mysql", vec![query]).expect("generate");

    for (i, (db_type, rust_type)) in cases.iter().enumerate() {
        let expected = format!("pub c_{i}: {rust_type},");
        assert!(
            code.contains(&expected),
            "{db_type} should map to {rust_type}; missing `{expected}` in:\n{code}"
        );
    }
}

#[test]
fn unknown_engine_is_rejected() {
    let err = generate("oracle", vec![]).expect_err("oracle is not supported");
    assert!(err.contains("oracle"), "expected the engine name in: {err}");
    assert!(
        err.contains("postgresql") && err.contains("mysql"),
        "expected the supported engines to be listed in: {err}"
    );
}

#[test]
fn missing_engine_still_generates_postgres() {
    // sqlc always sends settings, but requests built by hand (and older
    // releases) may not. Keep the historical default rather than failing.
    let request = GenerateRequest {
        plugin_options: b"{}".to_vec(),
        sqlc_version: "1.0.0-test".to_string(),
        ..Default::default()
    };
    let out = run_with_bytes(&request.encode_to_vec()).expect("generate");
    let resp = GenerateResponse::decode_from_slice(&out).unwrap();
    let code = String::from_utf8(resp.files[0].contents.clone()).unwrap();
    assert!(
        code.contains("sqlx::PgPool"),
        "expected the PostgreSQL default in:\n{code}"
    );
}
